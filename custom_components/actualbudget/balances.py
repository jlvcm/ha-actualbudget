"""Build sensor balances from the synced Actual SQLite database."""

from __future__ import annotations

from collections import Counter, defaultdict
from dataclasses import dataclass, field
from datetime import date, timedelta
from decimal import Decimal

from actual.queries import get_preference
from actual.utils.conversions import (
    cents_to_decimal,
    date_to_int,
    int_to_date,
    next_month,
)
from sqlalchemy import text
from sqlmodel import Session


@dataclass
class BudgetMonth:
    month: str
    budgeted: float
    spent: float


@dataclass
class Budget:
    name: str
    current: BudgetMonth
    previous: BudgetMonth
    accumulated_balance: Decimal
    total_budgeted: float


@dataclass
class Account:
    name: str
    balance: Decimal
    off_budget: bool
    closed: bool


@dataclass
class BudgetData:
    """Snapshot of all accounts and budgets at a point in time."""

    accounts: dict[str, Account] = field(default_factory=dict)
    budgets: dict[str, Budget] = field(default_factory=dict)


# The Actual account register sums top-level transactions (including split
# parents), not their children.
_ACCOUNT_BALANCES = text("""
    SELECT a.id, a.name, a.offbudget, a.closed, COALESCE(SUM(t.amount), 0) AS amount
    FROM accounts a
    LEFT JOIN transactions t ON t.acct = a.id AND t.isChild = 0
        AND t.date IS NOT NULL AND t.tombstone = 0
    WHERE a.tombstone = 0 AND a.name IS NOT NULL
    GROUP BY a.id
    ORDER BY a.sort_order, a.id
""")

# Mirror Actual's v_transactions_internal_alive and budget spending query.
# The views are generated by the JS client and need not exist in the sync copy.
# For budgets, each live split child belongs to its own mapped category and
# contributes only if its account is on budget. Never count the split parent.
_CATEGORY_SPENDING = text("""
    SELECT m.transferId AS category, t.date / 100 AS month, SUM(t.amount) AS amount
    FROM transactions t
    JOIN accounts a ON a.id = t.acct AND a.offbudget = 0
    JOIN category_mapping m ON m.id = t.category AND m.transferId IS NOT NULL
    LEFT JOIN transactions parent ON t.isChild = 1 AND parent.id = t.parent_id
    WHERE t.date >= :start AND t.date < :end
        AND COALESCE(t.tombstone, 0) = 0
        AND (t.isParent != 1 OR t.isParent IS NULL)
        AND (t.isChild = 0 OR parent.tombstone = 0)
    GROUP BY m.transferId, t.date / 100
""")

_CATEGORIES = text("""
    SELECT c.id, c.name, c.is_income, g.name AS group_name
    FROM categories c
    JOIN category_groups g ON g.id = c.cat_group AND g.tombstone = 0
    WHERE c.tombstone = 0 AND c.name IS NOT NULL
        AND (c.is_income = 0 OR :tracking)
    ORDER BY c.id
""")


def _sensor_names(rows, qualifier=lambda row: row.id):
    """Keep unambiguous legacy names; never merge rows with colliding names."""
    counts = Counter(row.name.lower() for row in rows)
    used = set(counts)
    for row in rows:
        name = row.name
        if counts[name.lower()] > 1:
            name = f"{name} ({qualifier(row) or row.id})"
            while name.lower() in used:
                name = f"{name} ({row.id})"
        used.add(name.lower())
        yield row, name


def _previous_month(month: date) -> date:
    return (month - timedelta(days=1)).replace(day=1)


def _month_snapshot(
    month: int, allocations: dict[int, tuple[int, bool]], spent: dict[int, int]
) -> BudgetMonth:
    amount, _ = allocations.get(month, (0, False))
    return BudgetMonth(
        month=str(month),
        budgeted=float(cents_to_decimal(amount)),
        spent=float(cents_to_decimal(spent.get(month, 0))),
    )


def read_balances(session: Session, today: date) -> BudgetData:
    """Read account registers and calculate category rollovers in one bulk pass."""
    data = BudgetData()
    accounts = session.execute(_ACCOUNT_BALANCES).all()
    for account, name in _sensor_names(accounts):
        data.accounts[name] = Account(
            name,
            cents_to_decimal(account.amount),
            bool(account.offbudget),
            bool(account.closed),
        )

    preference = get_preference(session, "budgetType")
    tracking = preference is not None and preference.value in ("tracking", "report")
    table = "reflect_budgets" if tracking else "zero_budgets"
    current = today.replace(day=1)
    previous = _previous_month(current)
    current_number = date_to_int(current, month_only=True)
    previous_number = date_to_int(previous, month_only=True)

    # Actual starts its budget spreadsheet three months before the first
    # top-level transaction (or the current month if there are none).
    first_date = session.execute(
        text("SELECT MIN(date) FROM transactions WHERE isChild = 0")
    ).scalar_one()
    start = current
    if first_date is not None:
        start = min(current, int_to_date(first_date).replace(day=1))
    for _ in range(3):
        start = _previous_month(start)

    months = [current]
    while months[-1] > start:
        months.append(_previous_month(months[-1]))
    month_numbers = [date_to_int(m, month_only=True) for m in reversed(months)]

    spent: dict[str, dict[int, int]] = defaultdict(dict)
    for row in session.execute(
        _CATEGORY_SPENDING,
        {"start": date_to_int(start), "end": date_to_int(next_month(current))},
    ):
        spent[row.category][row.month] = row.amount or 0

    allocations: dict[str, dict[int, tuple[int, bool]]] = defaultdict(dict)
    for row in session.execute(
        text(
            f"SELECT category, month, amount, carryover FROM {table} WHERE month <= :month"
        ),
        {"month": current_number},
    ):
        allocations[row.category][row.month] = (row.amount or 0, row.carryover == 1)

    categories = session.execute(_CATEGORIES, {"tracking": tracking}).all()
    for category, name in _sensor_names(categories, lambda row: row.group_name):
        category_allocations = allocations[category.id]
        category_spent = spent[category.id]
        balance = 0
        carryover = False
        for month in month_numbers:
            if not carryover:
                balance = 0 if tracking else max(0, balance)
            amount, carryover = category_allocations.get(month, (0, False))
            activity = category_spent.get(month, 0)
            balance += amount - activity if category.is_income else amount + activity

        total_budgeted = sum(amount for amount, _ in category_allocations.values())

        data.budgets[name] = Budget(
            name=name,
            current=_month_snapshot(
                current_number, category_allocations, category_spent
            ),
            previous=_month_snapshot(
                previous_number, category_allocations, category_spent
            ),
            accumulated_balance=cents_to_decimal(balance),
            total_budgeted=float(cents_to_decimal(total_budgeted)),
        )

    return data
